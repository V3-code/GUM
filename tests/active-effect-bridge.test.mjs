import assert from "node:assert/strict";
import test from "node:test";
import {
  activateEffectItemBridgeCarrier,
  buildEffectItemBridgeData,
  cleanupEffectItemBridgeCarrier,
  ensureEffectItemBridge,
  findEffectsGeneratedByBridge,
  getEffectItemBridgeData,
  isEffectItemBridgeApplicationActive
} from "../module/integrations/active-effect-bridge.mjs";

const setPath = (target, path, value) => {
  const parts = path.split(".");
  let cursor = target;
  for (const part of parts.slice(0, -1)) cursor = cursor[part] ??= {};
  cursor[parts.at(-1)] = value;
};

const makeEffectItem = () => {
  const item = {
    id: "effect-item",
    uuid: "Item.effect-item",
    name: "Chamas",
    type: "effect",
    documentName: "Item",
    isOwner: true,
    effects: [],
    async createEmbeddedDocuments(_type, documents) {
      const created = documents.map((data, index) => ({
        ...structuredClone(data),
        id: `bridge-${index}`,
        uuid: `${this.uuid}.ActiveEffect.bridge-${index}`,
        documentName: "ActiveEffect",
        parent: this,
        async update(changes) {
          for (const [path, value] of Object.entries(changes)) {
            if (path.includes(".")) setPath(this, path, value);
            else this[path] = structuredClone(value);
          }
        }
      }));
      this.effects.push(...created);
      return created;
    },
    async deleteEmbeddedDocuments(_type, ids) {
      this.effects = this.effects.filter(effect => !ids.includes(effect.id));
    }
  };
  return item;
};

test("builds and maintains one inert ActiveEffect bridge inside each Effect Item", async () => {
  const item = makeEffectItem();
  const source = buildEffectItemBridgeData(item);
  assert.equal(source.flags.gum.effectItemBridge.effectItemUuid, item.uuid);
  assert.deepEqual(source.changes, []);
  assert.equal(source.transfer, false);

  const bridge = await ensureEffectItemBridge(item);
  assert.equal(item.effects.length, 1);
  assert.equal(getEffectItemBridgeData(bridge).effectItemUuid, item.uuid);
  assert.equal(await ensureEffectItemBridge(item), bridge);
  assert.equal(item.effects.length, 1);
});

test("activates an Actor bridge once and routes it to the GUM Effect Item", async () => {
  const actor = { id: "actor", uuid: "Actor.actor", documentName: "Actor", effects: [] };
  const carrier = {
    id: "carrier",
    uuid: "Actor.actor.ActiveEffect.carrier",
    documentName: "ActiveEffect",
    parent: actor,
    disabled: false,
    origin: "Scene.scene.Region.region.RegionBehavior.behavior",
    flags: { gum: { effectItemBridge: { version: 1, effectItemUuid: "Item.effect-item" } } },
    async update(changes) { for (const [path, value] of Object.entries(changes)) setPath(this, path, value); }
  };
  actor.effects.push(carrier);
  const effectItem = { uuid: "Item.effect-item", name: "Chamas", type: "effect", documentName: "Item" };
  const calls = [];
  const result = await activateEffectItemBridgeCarrier(carrier, {
    resolveUuid: async () => effectItem,
    randomId: () => "application-1",
    buildTargets: targetActor => [{ actor: targetActor, document: targetActor }],
    applyEffect: async (...args) => calls.push(args)
  });

  assert.equal(result.applied, true);
  assert.equal(calls.length, 1);
  assert.equal(calls[0][0], effectItem);
  assert.equal(calls[0][2].applicationId, "application-1");
  assert.equal(calls[0][2].gumFlags.activeEffectBridge.carrierUuid, carrier.uuid);
  assert.equal(getEffectItemBridgeData(carrier).applicationId, "application-1");

  const repeated = await activateEffectItemBridgeCarrier(carrier, {
    resolveUuid: async () => effectItem,
    buildTargets: () => [],
    applyEffect: async () => calls.push("unexpected")
  });
  assert.equal(repeated.reason, "already-applied");
  assert.equal(calls.length, 1);
});

test("finds and removes only persistent effects generated by one bridge carrier", async () => {
  const actor = {
    documentName: "Actor",
    effects: [],
    async deleteEmbeddedDocuments(_type, ids, options) {
      this.deleted = { ids, options };
      this.effects = this.effects.filter(effect => !ids.includes(effect.id));
    }
  };
  const carrier = {
    id: "carrier",
    uuid: "Actor.actor.ActiveEffect.carrier",
    documentName: "ActiveEffect",
    parent: actor,
    flags: { gum: { effectItemBridge: { effectItemUuid: "Item.effect", applicationId: "application-1" } } }
  };
  const generated = { id: "generated", flags: { gum: { activeEffectBridge: { carrierUuid: carrier.uuid, applicationId: "application-1" } } } };
  const unrelated = { id: "unrelated", flags: { gum: { activeEffectBridge: { carrierUuid: "other" } } } };
  actor.effects.push(carrier, generated, unrelated);

  assert.deepEqual(findEffectsGeneratedByBridge(actor, carrier), [generated]);
  assert.deepEqual(await cleanupEffectItemBridgeCarrier(carrier), [generated.id]);
  assert.deepEqual(actor.deleted.ids, [generated.id]);
  assert.equal(actor.deleted.options.gumEffectBridgeCleanup, true);
  assert.ok(actor.effects.includes(unrelated));
});

test("rejects delayed bridge applications after the carrier disappears or is disabled", async () => {
  const context = {
    gumFlags: { activeEffectBridge: {
      carrierUuid: "Actor.actor.ActiveEffect.carrier",
      applicationId: "application-1"
    } }
  };
  assert.equal(await isEffectItemBridgeApplicationActive(context, { resolveUuid: async () => null }), false);
  assert.equal(await isEffectItemBridgeApplicationActive(context, { resolveUuid: async () => ({
    documentName: "ActiveEffect",
    parent: { documentName: "Actor" },
    disabled: true,
    flags: { gum: { effectItemBridge: { effectItemUuid: "Item.effect", applicationId: "application-1" } } }
  }) }), false);
  assert.equal(await isEffectItemBridgeApplicationActive({}, { resolveUuid: async () => null }), true);
});
